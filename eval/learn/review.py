"""Hand-review sheet of the learning study (eval/learn/PROTOCOL.md,
"Hand review"): every test question where K's and U0's verdicts differ,
then 20 judge-approved answers drawn with random.Random(45), 10 from U0
and then 10 from B (one generator, U0 drawn first; each pool sorted by
conversation, then QA index, before random.sample).

For each question: conversation, question, gold, the condition's answer
and verdict, and the text of its evidence turns (the valid dia_ids the
ask line parsed, looked up in locomo10.json).

  python3 eval/learn/review.py --work eval/learn/work/test \
      --locomo eval/locomo/data/locomo10.json --out eval/learn/review.md
"""

from __future__ import annotations

import argparse
import json
import os
import random
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "lme", "py"))

import common  # noqa: E402

TEST_CONVS = ("conv-26", "conv-41", "conv-42", "conv-43", "conv-44", "conv-48", "conv-50")
SEED = 45
PER_POOL = 10


def load(path: str) -> list[dict]:
    return common.read_jsonl(path) if os.path.exists(path) else []


def turn_texts(locomo: str, convs: list[str]) -> dict[str, dict[str, str]]:
    """conv -> dia_id -> "Speaker: text [shares a photo: caption]" (the
    ingested content, LocomoContent)."""
    with open(locomo, encoding="utf-8") as f:
        data = json.load(f)
    out = {}
    for s in data:
        if s["sample_id"] not in convs:
            continue
        m = {}
        conv = s["conversation"]
        for k, v in conv.items():
            if not re.fullmatch(r"session_\d+", k) or not isinstance(v, list):
                continue
            date = conv.get(f"{k}_date_time", "")
            for t in v:
                txt = f"{t['speaker']}: {t['text']}"
                if t.get("blip_caption"):
                    txt += f" [shares a photo: {t['blip_caption']}]"
                m[t["dia_id"]] = f"({date}) {txt}" if date else txt
        out[s["sample_id"]] = m
    return out


def qindex(qid: str) -> int:
    m = re.search(r"-q(\d+)$", qid)
    return int(m.group(1)) if m else 0


def collect(work: str, convs: list[str]) -> dict:
    d = {"answers": {}, "asks": {}}
    for c in ("U0", "K", "B"):
        d["answers"][c], d["asks"][c] = {}, {}
        for conv in convs:
            od = os.path.join(work, conv, "out")
            for r in load(os.path.join(od, f"{c}.test.answers.jsonl")):
                d["answers"][c][r["question_id"]] = {**r, "conv": conv}
            for r in load(os.path.join(od, f"{c}.test.ask.jsonl")):
                d["asks"][c][r["question_id"]] = r
    return d


def order_key(convs: list[str]):
    return lambda r: (convs.index(r["conv"]), qindex(r["question_id"]))


def differing(d: dict, convs: list[str]) -> list[str]:
    u0, k = d["answers"]["U0"], d["answers"]["K"]
    ids = [q for q in u0 if q in k and bool(u0[q]["verdict"]) != bool(k[q]["verdict"])]
    return sorted(ids, key=lambda q: order_key(convs)(u0[q]))


def sample_approved(d: dict, convs: list[str], seed: int = SEED, n: int = PER_POOL) -> list[tuple[str, str]]:
    """[(condition, question_id)]: n judge-approved U0 answers, then n of B,
    drawn with one random.Random(seed)."""
    rng = random.Random(seed)
    out = []
    for c in ("U0", "B"):
        pool = sorted((r for r in d["answers"][c].values() if r.get("verdict") is True), key=order_key(convs))
        out += [(c, r["question_id"]) for r in rng.sample(pool, min(n, len(pool)))]
    return out


def evidence_block(d: dict, qid: str, conv: str, texts: dict) -> list[str]:
    line = d["asks"]["U0"].get(qid) or d["asks"]["B"].get(qid) or d["asks"]["K"].get(qid) or {}
    ev = line.get("evidence") or {}
    keys = [t["key"] for t in ev.get("turns") or []]
    out = []
    for k in keys:
        out.append(f"  - `{k}` {texts.get(conv, {}).get(k, '(turn not found)')}")
    if ev.get("invalid"):
        out.append(f"  - invalid evidence ids (not scored): {', '.join(ev['invalid'])}")
    if not out:
        out.append("  - (no valid evidence)")
    return out


def one_line(s) -> str:
    return " ".join(str(s).split()).replace("|", "\\|")


def verdict(r: dict) -> str:
    return "CORRECT" if r.get("verdict") else "WRONG"


def render(d: dict, convs: list[str], texts: dict) -> str:
    L = ["# Hand review: learning study", "",
         "Generated by `eval/learn/review.py` (PROTOCOL.md, Measures: hand review). Verdicts are the judge's.", ""]
    diff = differing(d, convs)
    L += [f"## 1. Test questions where K and U0 differ ({len(diff)})", ""]
    for i, q in enumerate(diff, 1):
        u, k = d["answers"]["U0"][q], d["answers"]["K"][q]
        L += [f"### 1.{i} {u['conv']} `{q}` ({u.get('category_name') or u.get('category')})", "",
              f"- **Question:** {one_line(u['question'])}", f"- **Gold:** {one_line(u['gold'])}",
              f"- **U0** ({verdict(u)}): {one_line(u['answer'])}", f"- **K** ({verdict(k)}): {one_line(k['answer'])}",
              "- **Evidence:**"] + evidence_block(d, q, u["conv"], texts) + [""]
    sample = sample_approved(d, convs)
    L += [f"## 2. Judge-approved answers, sampled with random.Random({SEED}) ({len(sample)}: U0 then B)", ""]
    for i, (c, q) in enumerate(sample, 1):
        r = d["answers"][c][q]
        L += [f"### 2.{i} {c}, {r['conv']} `{q}` ({r.get('category_name') or r.get('category')})", "",
              f"- **Question:** {one_line(r['question'])}", f"- **Gold:** {one_line(r['gold'])}",
              f"- **{c}** ({verdict(r)}): {one_line(r['answer'])}", "- **Evidence:**"] + evidence_block(d, q, r["conv"], texts) + [""]
    L += ["## Reviewer notes", "", "(For each item: is the verdict right? Does the answer follow from the evidence?)", ""]
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--work", required=True)
    ap.add_argument("--locomo", default="eval/locomo/data/locomo10.json")
    ap.add_argument("--convs", help="space-separated conversations (default: the 7 test conversations)")
    ap.add_argument("--out", default=os.path.join(HERE, "review.md"))
    args = ap.parse_args(argv)
    convs = args.convs.split() if args.convs else list(TEST_CONVS)
    d = collect(args.work, convs)
    md = render(d, convs, turn_texts(args.locomo, convs))
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(md)
    print(f"wrote {args.out}: {len(differing(d, convs))} differing, {len(sample_approved(d, convs))} sampled", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
